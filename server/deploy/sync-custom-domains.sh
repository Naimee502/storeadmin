#!/usr/bin/env bash
# ─────────────────────────────────────────────────────────────────────────────
# Custom domains — automatic nginx site + SSL for every business's own domain.
#
# Runs from cron every 5 minutes (see bottom of this file for the one-time
# install). Each run:
#   1. reads the list of custom domains saved in Business Settings
#      (http://127.0.0.1:4000/internal/custom-domains — localhost only);
#   2. for a domain whose DNS already points at this server, writes an nginx
#      site serving the customer website (clientweb/dist), reloads nginx and
#      gets a free Let's Encrypt certificate with certbot (auto-renewing);
#   3. removes the nginx site of a domain that was taken out of Business
#      Settings.
# A domain whose DNS is not pointing here yet is skipped and retried next run,
# so the admin only saves the domain and sets the A record — nothing else.
#
# Log: /var/log/custom-domains.log
# ─────────────────────────────────────────────────────────────────────────────
set -u

API="http://127.0.0.1:4000/internal/custom-domains"
SERVER_IP="72.61.226.71"
WEB_ROOT="/var/www/pos_billing_erp/clientweb/dist"
CERT_EMAIL="info@digisysindiatech.com"
AVAIL="/etc/nginx/sites-available"
ENABLED="/etc/nginx/sites-enabled"
PREFIX="cd-"                                  # our files: cd-<domain>
STATE="/var/lib/custom-domains"               # certbot failure back-off
LOG="/var/log/custom-domains.log"
RETRY_AFTER_FAIL=3600                         # seconds (Let's Encrypt rate limits)

mkdir -p "$STATE"
exec 9>"$STATE/.lock"
flock -n 9 || exit 0                          # previous run still busy

log() { echo "$(date '+%F %T') $*" >> "$LOG"; }
resolves_here() { getent ahostsv4 "$1" 2>/dev/null | awk '{print $1}' | grep -qx "$SERVER_IP"; }
valid() { [[ "$1" =~ ^[a-z0-9]([a-z0-9-]*[a-z0-9])?(\.[a-z0-9]([a-z0-9-]*[a-z0-9])?)+$ ]]; }

RESP="$(curl -fsS --max-time 10 "$API" 2>/dev/null)" || { log "API not reachable — skipped"; exit 0; }
[ "$(echo "$RESP" | head -n1)" = "OK" ] || { log "unexpected API answer — skipped"; exit 0; }
DOMAINS="$(echo "$RESP" | tail -n +2 | tr -d '\r' | sed '/^$/d')"

changed=0

# ── Add / finish domains ─────────────────────────────────────────────────────
for d in $DOMAINS; do
  valid "$d" || { log "skip invalid name: $d"; continue; }
  conf="$AVAIL/$PREFIX$d"

  # Already live with SSL — nothing to do.
  if [ -f "$conf" ] && grep -q "ssl_certificate" "$conf"; then continue; fi

  if ! resolves_here "$d"; then
    # Quiet: logged once per hour at most.
    stamp="$STATE/dns-$d"
    if [ ! -f "$stamp" ] || [ $(( $(date +%s) - $(stat -c %Y "$stamp") )) -gt 3600 ]; then
      log "waiting for DNS: $d does not point to $SERVER_IP yet"; touch "$stamp"
    fi
    continue
  fi
  rm -f "$STATE/dns-$d"

  names="$d"
  resolves_here "www.$d" && names="$d www.$d"

  # 1) plain-HTTP site (certbot needs it to prove the domain)
  if [ ! -f "$conf" ]; then
    cat > "$conf" <<EOF
# Auto-generated by sync-custom-domains.sh — do not edit by hand.
server {
    listen 80;
    listen [::]:80;
    server_name $names;

    root $WEB_ROOT;
    index index.html;

    location / {
        try_files \$uri \$uri/ /index.html;
    }
}
EOF
    ln -sf "$conf" "$ENABLED/$PREFIX$d"
    if nginx -t >/dev/null 2>&1; then
      systemctl reload nginx; changed=1; log "nginx site added: $names"
    else
      log "nginx -t failed for $d — site removed"; rm -f "$ENABLED/$PREFIX$d" "$conf"; continue
    fi
  fi

  # 2) SSL (back off an hour after a failure — Let's Encrypt rate limits)
  fail="$STATE/certfail-$d"
  if [ -f "$fail" ] && [ $(( $(date +%s) - $(stat -c %Y "$fail") )) -lt $RETRY_AFTER_FAIL ]; then continue; fi
  args=(); for n in $names; do args+=(-d "$n"); done
  if certbot --nginx --non-interactive --agree-tos -m "$CERT_EMAIL" --redirect "${args[@]}" >> "$LOG" 2>&1; then
    rm -f "$fail"; changed=1; log "SSL ready: https://$d"
  else
    touch "$fail"; log "certbot failed for $d — will retry in 1 hour"
  fi
done

# ── Remove domains no longer in Business Settings ───────────────────────────
for conf in "$AVAIL"/"$PREFIX"*; do
  [ -e "$conf" ] || continue
  d="${conf##*/$PREFIX}"
  if ! echo "$DOMAINS" | grep -qx "$d"; then
    rm -f "$ENABLED/$PREFIX$d" "$conf"
    changed=1; log "removed site (domain no longer saved): $d"
  fi
done

if [ "$changed" = 1 ]; then nginx -t >/dev/null 2>&1 && systemctl reload nginx; fi
exit 0

# ─────────────────────────────────────────────────────────────────────────────
# ONE-TIME INSTALL on the VPS (as root):
#
#   cp /var/www/pos_billing_erp/server/deploy/sync-custom-domains.sh /usr/local/bin/
#   chmod +x /usr/local/bin/sync-custom-domains.sh
#   echo '*/5 * * * * root /usr/local/bin/sync-custom-domains.sh' > /etc/cron.d/custom-domains
#
# Run it by hand once to check:   /usr/local/bin/sync-custom-domains.sh
# Watch what it does:             tail -f /var/log/custom-domains.log
# ─────────────────────────────────────────────────────────────────────────────
